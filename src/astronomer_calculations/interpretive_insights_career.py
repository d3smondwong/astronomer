def _modulate_career_effect_by_constitution(effect: dict, dm_score: int) -> dict:
    """Modulate cycle career effect 解读 and 强度 based on constitutional strength.

    Args:
        effect: Career effect dict with '解读' and '强度' keys
        dm_score: Day Master strength (0-5)

    Returns:
        Modified effect dict with constitutional context added to 解读 and adjusted 强度
    """
    modified = effect.copy()
    original_jieyue = modified.get("解读", "")

    if dm_score <= 1:
        # Weak constitution: amplify negative impact, downgrade positive opportunity
        strength = modified.get("强度", "")
        effect_type = modified.get("作用类型", "")

        # For disruptive effects, upgrade severity; for opportunities, downgrade
        if (
            "冲" in effect_type
            or "void" in effect_type.lower()
            or "反" in effect_type
            or "伏" in effect_type
        ):
            # Negative effect: amplify
            modified["解读"] = (
                original_jieyue
                + " 因先天体质偏弱，此影响更为显著，职业推进受阻更严重，需格外谨慎与调理。"
            )
            if strength == "中等影响":
                modified["强度"] = "显著影响"
            elif strength == "显著影响":
                modified["强度"] = "强势主流"
        else:
            # Positive effect: downgrade/caution
            modified["解读"] = (
                original_jieyue
                + " 但因体质脆弱，虽有机遇但执行力受限，需健康保障才能真正把握机遇。"
            )
            if strength == "显著影响":
                modified["强度"] = "中等影响"
            elif strength == "中等影响":
                modified["强度"] = "大幅衰减"

    elif dm_score >= 3:
        # Strong constitution: emphasize resilience and opportunity capture
        strength = modified.get("强度", "")
        effect_type = modified.get("作用类型", "")

        # For positive effects, upgrade; for negative, downgrade recovery impact
        if (
            "冲" in effect_type
            or "void" in effect_type.lower()
            or "反" in effect_type
            or "伏" in effect_type
        ):
            # Negative effect: downgrade severity (can recover)
            modified["解读"] = (
                original_jieyue
                + " 因体质强健，能较快调适与反弹，职业压力尚在可控范围。"
            )
            if strength == "强势主流":
                modified["强度"] = "显著影响"
            elif strength == "显著影响":
                modified["强度"] = "中等影响"
        else:
            # Positive effect: emphasize full capture
            modified["解读"] = (
                original_jieyue
                + " 因体质强健，可充分把握机遇，事半功倍，是突破的黄金期。"
            )
            if strength == "中等影响":
                modified["强度"] = "显著影响"
            elif strength == "显著影响":
                modified["强度"] = "强势主流"

    # dm_score == 2 (moderate): no adjustment, use as-is

    return modified


