def _get_career_star_positions(shi_shen: dict, bazi: dict) -> dict:
    """
    Scans shi_shen["十神"] for 正官/七杀 appearances across all four pillars.
    Also captures the element of each career star from the pillar's stem or branch.
    Returns:
      {
        "in_stems":      ["年干", ...],
        "in_branches":   ["年支本气", ...],
        "all":           [...combined...],
        "official":      [...official positions...],
        "killer":        [...killer positions...],
        "elements":      {"年干": "木", ...}  # element for each position
      }
    """
    in_stems, in_branches = [], []
    official_pos, killer_pos = [], []
    elements = {}
    ba_zi = bazi.get("八字", {})

    for pillar in PILLARS:
        p = shi_shen.get(pillar, {})
        pillar_bazi = ba_zi.get(pillar, {})
        stem = pillar_bazi.get("天干")
        branch = pillar_bazi.get("地支")

        stem_god = p.get("天干十神")
        if stem_god in CAREER_STARS:
            stem_label = pillar[:1] + "干"
            in_stems.append(stem_label)
            if stem in STEM_ELEMENT_MAP:
                elements[stem_label] = STEM_ELEMENT_MAP[stem]
            if stem_god == "正官":
                official_pos.append(stem_label)
            else:
                killer_pos.append(stem_label)

        for tier in BRANCH_TIERS:
            branch_god = p.get("地支十神", {}).get(tier)
            if branch_god in CAREER_STARS:
                branch_label = pillar[:1] + "支" + tier
                in_branches.append(branch_label)
                # For branch positions, use the branch's element
                if branch in BRANCH_ELEMENT_MAP:
                    elements[branch_label] = BRANCH_ELEMENT_MAP[branch]
                if branch_god == "正官":
                    official_pos.append(branch_label)
                else:
                    killer_pos.append(branch_label)

    return {
        "in_stems": in_stems,
        "in_branches": in_branches,
        "all": in_stems + in_branches,
        "official": official_pos,
        "killer": killer_pos,
        "elements": elements,
    }


def _get_star_positions_by_type(
    shi_shen: dict, star_set: set, sub_type_map: dict[str, str]
) -> dict:
    """
    Generic scanner for ten-god positions. Reduces code duplication across scanners.

    Args:
        shi_shen: The 十神 data structure
        star_set: Set of ten-god types to scan for (e.g., YIN_STARS)
        sub_type_map: Mapping from ten-god to sub-category key (e.g., {"正印": "zheng_yin", "偏印": "pian_yin"})

    Returns dict with keys: in_stems, in_branches, all, plus sub-category keys
    """
    in_stems, in_branches = [], []
    subs = {key: [] for key in set(sub_type_map.values())}

    for pillar in PILLARS:
        p = shi_shen.get(pillar, {})
        stem_god = p.get("天干十神")
        if stem_god in star_set:
            stem_label = pillar[:1] + "干"
            in_stems.append(stem_label)
            if stem_god in sub_type_map:
                subs[sub_type_map[stem_god]].append(stem_label)

        for tier in BRANCH_TIERS:
            branch_god = p.get("地支十神", {}).get(tier)
            if branch_god in star_set:
                branch_label = pillar[:1] + "支" + tier
                in_branches.append(branch_label)
                if branch_god in sub_type_map:
                    subs[sub_type_map[branch_god]].append(branch_label)

    return {
        "in_stems": in_stems,
        "in_branches": in_branches,
        "all": in_stems + in_branches,
        **subs,
    }


