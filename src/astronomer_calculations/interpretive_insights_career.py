    if len(weak_elements) != len(
        [p for p in csp["in_stems"] + csp["in_branches"] if p in csp["elements"]]
    ):
        return None

    # Remove duplicates while preserving first-seen order for stable output
    unique_elements = list(dict.fromkeys(weak_elements))
    element_str = (
        "、".join(unique_elements) if len(unique_elements) > 1 else unique_elements[0]
    )
    strength_str = (
        wu_xing.get("五行力量分析", {}).get(unique_elements[0], {}).get("旺衰", "")
    )

    # Nuance based on constitutional strength
    if dm_score >= 3:
        interpretation = "官星微弱，职业心志虽有，但因体质强健，可通过自身努力与持续行动补偿，适合独立创业或自我管理，抗拒权威而能自驱。"
