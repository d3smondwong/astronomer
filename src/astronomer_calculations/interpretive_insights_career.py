def _void_branch_positions(branch_chars: dict, xun_kong: dict) -> set:
    """
    Returns set of branch position keys where that pillar's branch falls in 旬空.
    """
    voided = set()
    for branch_key, branch_char in branch_chars.items():
        pillar_key = branch_key[:1] + "柱"
        xun_kong_str = xun_kong.get("旬空", {}).get(pillar_key, {}).get("旬空", "")
        if branch_char in xun_kong_str:
            voided.add(branch_key)
    return voided


def _has_chong_xing_on_pillar(pillar_name: str, interactions: dict) -> bool:
    """Return True if pillar has active 六冲 or 三刑.

    Args:
        pillar_name: Name of pillar (e.g., "月柱")
        interactions: Either full interactions dict with "作用" key, or just the "作用" dict
    """
    # Handle both full interactions dict and extracted "作用" dict
    if "柱位动态" in interactions:
        # Already extracted "作用" dict
        pillar_data = interactions.get("柱位动态", {}).get(pillar_name, {})
    else:
        # Full interactions dict
        pillar_data = (
            interactions.get("作用", {}).get("柱位动态", {}).get(pillar_name, {})
        )
    for tier_items in pillar_data.values():
        if not isinstance(tier_items, list):
            continue
        for item in tier_items:
            if item.get("类型") in {"六冲", "无恩之刑", "恃势之刑", "无礼之刑", "自刑"}:
                if item.get("强度") in ACTIVE_STRENGTHS:
                    return True
    return False


def _get_current_decade(da_yun: dict) -> dict | None:
    """Return the decade dict with 当运 == True, or None if not found."""
    cycles = da_yun.get("大运", {}).get("大运周期", [])
    for cycle in cycles[1:]:
        if cycle.get("当运"):
            return cycle
    return None


def _decade_has_career(decade: dict) -> bool:
    """True if the decade's 运柱 contains 官杀 or significant ten-god impact."""
    run_zhu = decade.get("运柱", {})
    if not isinstance(run_zhu, dict):
        return False
    shi_shen = run_zhu.get("十神", {})
    if shi_shen.get("天干", {}).get("十神") in CAREER_STARS:
        return True
    for tier in BRANCH_TIERS:
        tier_data = shi_shen.get(tier)
        if isinstance(tier_data, dict) and tier_data.get("十神") in CAREER_STARS:
            return True
    return False


