def _pattern_career_combined_with_dm(
    interactions: dict, dm_stem: str, csp: dict
) -> dict | None:
    if not csp["in_stems"]:
        return None
    # Check if DM stem combines with any 官星 stem via 天干合
    # Search through 柱位动态 for 天干合 interactions
    pillar_data = interactions.get("作用", {}).get("柱位动态", {})
    career_stem_pillars = {pos[0] + "柱" for pos in csp["in_stems"]}
    career_stem_labels = set(csp["in_stems"])

    for pillar, tier_dict in pillar_data.items():
        # Search through all tiers (第一梯队, 第二梯队, 第三梯队)
        for tier_list in tier_dict.values():
            if not isinstance(tier_list, list):
                continue
            for item in tier_list:
                if item.get("类型") != "天干合":
                    continue
                if item.get("强度") not in ACTIVE_STRENGTHS:
                    continue
                # Check if DM stem and a career star stem are combined
                detail = item.get("组合明细", {})
                stems_in_combo = [v for v in detail.values() if isinstance(v, str)]
                if dm_stem not in stems_in_combo:
                    continue
                detail_keys = set(detail.keys())
                has_career_key = bool(
                    (detail_keys & career_stem_pillars)
                    or (detail_keys & career_stem_labels)
                )
                if has_career_key:
                    return {
                        "解读": "日主与官星相合，职业与自我完全融合，工作即生活，事业是自我表达的载体。",
                        "依据": f"天干合: {dm_stem} 与官星相合；强度: {item.get('强度')}",
                    }
    return None


def _pattern_officer_seal_chain(
    csp: dict, yin_pos: dict, wu_xing: dict, dm_element: str
) -> dict | None:
    if not (csp["all"] and yin_pos["all"]):
        return None

    # Get the actual career star element (from csp which already captured it)
    career_element = None
    for pos in csp["in_stems"] + csp["in_branches"]:
        if pos in csp["elements"]:
            career_element = csp["elements"][pos]
            break

    # Get the actual yin star element
    yin_element = YIN_ELEMENT_MAP.get(dm_element)

    if not career_element or not yin_element:
        return None

    # Verify they're in generation relationship (官星元素 generates 印星元素 in the cycle)
    if FOOD_GOD_HURT_OFFICER_ELEMENT_MAP.get(career_element) != yin_element:
        return None

    # Check strength: at least one must be truly strong, both must not be weak
    career_strength = wu_xing.get("五行力量分析", {}).get(career_element, {})
    yin_strength = wu_xing.get("五行力量分析", {}).get(yin_element, {})

    career_tier = career_strength.get("旺衰", "")
    yin_tier = yin_strength.get("旺衰", "")

    # Pattern fires if: generation relationship exists AND at least one is strong (偏旺+) AND both avoid extreme weakness
    truly_strong = {"偏旺", "极旺", "极亢"}
    not_weak = {"中和", "偏旺", "极旺", "极亢"}

    has_truly_strong = (career_tier in truly_strong) or (yin_tier in truly_strong)
    both_acceptable = (career_tier in not_weak) and (yin_tier in not_weak)

    if has_truly_strong and both_acceptable:
        return {
            "解读": "官印相生，权力与知识并行，职业路径兼具权威与信誉，学而优则仕的典型。",
            "依据": f"官星元素{career_element}生印星元素{yin_element}; 官星旺度: {career_tier}; 印星旺度: {yin_tier}",
        }
    return None


