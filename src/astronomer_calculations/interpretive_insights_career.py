    dm_stem = day_master.get("天干")
    dm_score = day_master.get("强弱分数", 0)

    # Organize shen_sha by pillar
    shen_sha = {}
    for pillar in PILLARS:
        pillar_key = pillar
        shen_sha[pillar] = shen_sha_raw.get("柱位神煞", {}).get(pillar_key, {})

