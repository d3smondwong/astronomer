# ── Synthesis ──────────────────────────────────────────────────────────────────


def _synthesize_career_patterns(fired_patterns: dict) -> dict:
    """
    Synthesize fired patterns into:
    - 主格局 (primary pattern name) or None
    - 辅助来源 (list of supplementary names)
    - 风险因素 (list of risk names)
    - 综合解读 (synthesized narrative)
    """
    primary = None
    for p_id in fired_patterns:
        if p_id in PRIMARY_PATTERNS:
            primary = fired_patterns[p_id].get("格局名称")
            break

    supp = [
        fired_patterns[p_id].get("格局名称")
        for p_id in fired_patterns
        if p_id in SUPPLEMENTARY_IDS
    ]
    risk = [
        fired_patterns[p_id].get("格局名称")
        for p_id in fired_patterns
        if p_id in RISK_IDS
    ]

    has_supp = bool(supp)
    has_risk = bool(risk)

    template_dict = _SYNTH.get(primary, _SYNTH_DEFAULT if primary else _SYNTH[None])
    template = template_dict.get(
        (has_supp, has_risk), _SYNTH_DEFAULT[(has_supp, has_risk)]
    )

    supp_str = "、".join(supp) if supp else ""
    risk_str = "、".join(risk) if risk else ""
    synth_text = template.format(
        supp_str=supp_str,
        risk_str=risk_str,
        anchor_name=primary or "命盘",
    )

    return {
        "主格局": primary,
        "辅助来源": supp,
        "风险因素": risk,
        "综合解读": synth_text,
    }


