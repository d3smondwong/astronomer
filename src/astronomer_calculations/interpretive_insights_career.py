    wealth_pos = {}
    for pillar in PILLARS:
        p = shi_shen.get(pillar, {})
        if p.get("天干十神") in WEALTH_STARS:
            wealth_pos[pillar] = True
    wealth_pos = {"all": list(wealth_pos.keys())}

    branch_chars = _get_branch_chars(bazi)
    voided_branches = _void_branch_positions(branch_chars, xun_kong)
    current_decade = _get_current_decade(da_yun)

    # Fire all pattern checkers
    fired = {}

